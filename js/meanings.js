/** rankを色クラスに */
window.rankClass = function (rank) {
  if (rank === '大吉') return 'rank-daikichi';
  if (rank === '吉' || rank === '中吉') return 'rank-kichi';
  if (rank === '半吉') return 'rank-hankichi';
  if (rank === '大凶') return 'rank-daikyou';
  if (rank === '凶' || rank === '注意') return 'rank-kyou';
  return 'rank-none';
};

